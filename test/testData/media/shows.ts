function makeEpisodes(
  showId: string,
  season: string,
  entries: Array<{
    title: string;
    slug: string;
    duration: number;
    durationLimit?: number;
  }>,
): Episode[] {
  return entries.map((entry, index) => {
    const durationLimit =
      entry.durationLimit ?? (entry.duration > 1800 ? 3600 : 1800);
    return createEpisode(
      season,
      String(index + 1),
      index + 1,
      `/path/shows/${showId}/${entry.slug}.mp4`,
      entry.title,
      `${showId}-${entry.slug}`,
      showId,
      entry.duration,
      durationLimit,
      entry.duration > durationLimit,
      MediaType.Episode,
      [],
    );
  });
}

